_TYPE_MAP = {
    "uuid":        lambda: String(36),
    "text":        lambda: Text(),
    "timestamptz": lambda: DateTime(timezone=True),
    "jsonb":       lambda: JSON(),
    "boolean":     lambda: Boolean(),
    "bigint":      lambda: BigInteger(),
    "integer":     lambda: Integer(),
    "numeric":     lambda: Numeric(),
}


def _supports_schemas(engine: Engine) -> bool:
    return engine.dialect.name != "sqlite"


def _make_column(name: str, type_token: str) -> Column:
    # "numeric" carries an optional precision/scale bound, e.g. "numeric(10,2)".
    # Strip it to find the base factory, then apply the bound if present.
    base = type_token.split("(", 1)[0].strip()
    factory = _TYPE_MAP.get(base)
    if factory is None:
        raise ValueError(f"Unknown ETL column type token: {type_token!r}")
    if base == "numeric" and "(" in type_token:
        bound = type_token[type_token.index("(") + 1: type_token.rindex(")")]
        parts = [p.strip() for p in bound.split(",") if p.strip()]
        try:
            nums = [int(p) for p in parts]
        except ValueError:
            nums = []
        col_type = Numeric(*nums) if nums else factory()
    else:
        col_type = factory()
    return Column(name, col_type, primary_key=(name == "id"), nullable=(name != "id"))


def ensure_etl_tables(engine: Engine, schema: str = "etl") -> dict[str, str]:
    """Create the three ETL tables if they don't already exist.

    Returns a mapping ``{logical_name: physical_fullname}`` so callers can
    reason about the actual table location regardless of schema support.
    """
    use_schemas = _supports_schemas(engine)
    schema_arg = schema if use_schemas else None
    name_prefix = "" if use_schemas else f"{schema}_"

    if use_schemas:
        insp = inspect(engine)
        if schema not in insp.get_schema_names():
            with engine.begin() as conn:
                conn.execute(CreateSchema(schema))
            log.info("Created ETL schema %s", schema)

    md = MetaData(schema=schema_arg)
    physical: dict[str, str] = {}
    for tname, cols in ETL_TABLES_SPEC.items():
        physical_name = f"{name_prefix}{tname}"
        Table(
            physical_name, md,
            *[_make_column(c, t) for c, t in cols],
            schema=schema_arg,
        )
        physical[tname] = f"{schema}.{physical_name}" if use_schemas else physical_name

    md.create_all(engine, checkfirst=True)
    log.info(
        "ETL schema ready — %d tables ensured (%s)",
        len(ETL_TABLES_SPEC),
        ", ".join(physical.values()),
    )
    return physical
